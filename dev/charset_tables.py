def constructor(name):
    parts = name.replace("_", "-").split("-")
    return "".join(part[:1].upper() + part[1:].lower() for part in parts)


def literal(codepoint):
    if 0x20 <= codepoint < 0x7F and chr(codepoint) not in '"\\':
        return '"%s"' % chr(codepoint)
    return '"\\u{%X}"' % codepoint


def main(checkout, commit, out):
    checkout = pathlib.Path(checkout)
    groups = json.loads((checkout / "encodings.json").read_text())
    indexes = json.loads((checkout / "indexes.json").read_text())

    labels = []
    single_byte = []
    for group in groups:
        for encoding in group["encodings"]:
            for label in encoding["labels"]:
                labels.append((label, encoding["name"]))
            if group["heading"] == "Legacy single-byte encodings":
                single_byte.append(encoding["name"])

    lines = [HEADER.format(commit=commit)]
    lines.append("/// The canonical WHATWG name for a trimmed, lowercase label.")
    lines.append("pub fn encoding(label: String) -> Result(String, Nil) {")
    lines.append("  case label {")
    for label, name in sorted(labels):
        lines.append('    "%s" -> Ok("%s")' % (label, name))
    lines.append("    _ -> Error(Nil)")
    lines.append("  }")
    lines.append("}")
    lines.append("")

    lines.append("pub type Table {")
    for name in single_byte:
        lines.append("  " + constructor(name))
    lines.append("}")
    lines.append("")

    lines.append("pub fn table(name: String) -> Result(Table, Nil) {")
    lines.append("  case name {")
    for name in single_byte:
        lines.append('    "%s" -> Ok(%s)' % (name, constructor(name)))
    lines.append("    _ -> Error(Nil)")
    lines.append("  }")
    lines.append("}")
    lines.append("")

    lines.append("/// The string for a byte 0x80-0xFF, or \"\" if the index has no entry.")
    lines.append("pub fn high_byte(table: Table, byte: Int) -> String {")
    lines.append("  case table {")
    for name in single_byte:
        function = name.lower().replace("-", "_")
        lines.append("    %s -> %s(byte)" % (constructor(name), function))
    lines.append("  }")
    lines.append("}")

    for name in single_byte:
        # ISO-8859-8-I shares the ISO-8859-8 index.
        index = indexes[name.lower().removesuffix("-i")]
        assert len(index) == 128, name
        function = name.lower().replace("-", "_")
        lines.append("")
        lines.append("fn %s(byte: Int) -> String {" % function)
        lines.append("  case byte {")
        for offset, codepoint in enumerate(index):
            if codepoint is not None:
                lines.append("    %d -> %s" % (0x80 + offset, literal(codepoint)))
        lines.append('    _ -> ""')
        lines.append("  }")
        lines.append("}")

    pathlib.Path(out).write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], sys.argv[3])
